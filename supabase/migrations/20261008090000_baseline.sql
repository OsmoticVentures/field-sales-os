CREATE OR REPLACE FUNCTION public.nb_accounts_near(p_lat double precision, p_lng double precision, p_radius_m double precision DEFAULT 25000)
 RETURNS TABLE(id text, name text, dba text, channel text, street text, city text, state text, postal text, lat double precision, lng double precision, phone text, website text, lifecycle text, last_order_at date, expected_reorder_at date, do_not_visit boolean, quirks text, origin nb_data_origin, distance_m double precision, tier text, fit double precision, engagement double precision)
 LANGUAGE sql
 STABLE
AS $function$
  select
    a.id, a.name, a.dba, a.channel, a.street, a.city, a.state, a.postal,
    a.lat, a.lng, a.phone, a.website, a.lifecycle,
    a.last_order_at, a.expected_reorder_at, a.do_not_visit, a.quirks, a.origin,
    st_distance(a.geo, st_setsrid(st_makepoint(p_lng, p_lat), 4326)::geography) as distance_m,
    t.tier::text, t.fit, t.engagement
  from nb_accounts a
  left join nb_v_account_tier t on t.account_id = a.id
  where a.geo is not null
    and a.closed_at is null
    and st_dwithin(a.geo, st_setsrid(st_makepoint(p_lng, p_lat), 4326)::geography, p_radius_m)
  order by distance_m asc
$function$;

