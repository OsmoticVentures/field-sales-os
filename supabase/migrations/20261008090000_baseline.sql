CREATE OR REPLACE FUNCTION public.nb_app_error_hit(p_fingerprint text, p_kind text, p_route text, p_message text, p_top_frame text, p_stack text, p_rep_id text, p_commit_sha text, p_hits integer DEFAULT 1)
 RETURNS void
 LANGUAGE plpgsql
AS $function$
declare
  inserted boolean;
begin
  insert into nb_app_errors as e
    (fingerprint, kind, route, message, top_frame, sample_stack, count, rep_id, commit_sha)
  values (
    left(p_fingerprint, 40), p_kind, left(coalesce(p_route, ''), 200),
    left(coalesce(p_message, ''), 500), left(coalesce(p_top_frame, ''), 300),
    left(coalesce(p_stack, ''), 4000), greatest(1, least(coalesce(p_hits, 1), 10000)),
    left(p_rep_id, 40), left(p_commit_sha, 40)
  )
  on conflict (fingerprint) do update set
    count        = least(e.count + greatest(1, least(coalesce(p_hits, 1), 10000)), 2000000000),
    last_seen    = now(),
    updated_at   = now(),
    rep_id       = coalesce(left(excluded.rep_id, 40), e.rep_id),
    commit_sha   = coalesce(excluded.commit_sha, e.commit_sha),
    sample_stack = case when excluded.sample_stack <> '' then excluded.sample_stack else e.sample_stack end,
    status       = case when e.status = 'fixed'
                          and excluded.commit_sha is distinct from e.commit_sha
                        then 'new' else e.status end
  returning (xmax = 0) into inserted;

  if inserted then
    delete from nb_app_errors
     where fingerprint in (
       select fingerprint from nb_app_errors
        order by last_seen desc offset 500);
  end if;
end $function$;

