CREATE OR REPLACE FUNCTION public.nb_deals_require_evidence()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
declare
  ord     constant nb_deal_stage[] := enum_range(null::nb_deal_stage);
  old_pos int;
  new_pos int;
  ev      int;
begin
  if new.stage is not distinct from old.stage then
    return new;
  end if;

  select array_position(ord, old.stage) into old_pos;
  select array_position(ord, new.stage) into new_pos;

  -- Regression or marking lost: always allowed, no evidence demanded.
  if new.stage = 'closed_lost' or new_pos < old_pos then
    return new;
  end if;

  -- Forward move: an evidence row for this transition must already exist.
  -- The application inserts nb_deal_stage_events FIRST, then updates deals.stage.
  select count(*) into ev
  from nb_deal_stage_events e
  where e.deal_id = new.id
    and e.to_stage = new.stage
    and e.at > now() - interval '1 minute'
    and (e.evidence_activity_id is not null or length(coalesce(e.evidence_note,'')) > 0);

  if ev = 0 then
    raise exception
      'deal % cannot advance %  ->  % without evidence. Insert a nb_deal_stage_events row citing the activity that satisfied the exit criterion first.',
      new.id, old.stage, new.stage;
  end if;

  return new;
end;
$function$;

